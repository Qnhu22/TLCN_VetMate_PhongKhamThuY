
/* =========================================================
   VETMATE - MEDICAL / PET MANAGEMENT
   File: database/04_medical_pet.sql

   Prerequisites:
   - 01_create_schemas.sql
   - 02_auth.sql

   Tables:
   - medical.ownerProfiles
   - medical.species
   - medical.breeds
   - medical.pets
   ========================================================= */

BEGIN;

/* =========================================================
   1. OWNER PROFILES
   User 1 ---- 0..1 OwnerProfile
   ========================================================= */

CREATE TABLE IF NOT EXISTS medical."ownerProfiles" (
    "ownerID" BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    "userID" BIGINT
        NOT NULL
        UNIQUE,

    "address" TEXT,

    "emergencyPhone" VARCHAR(20),

    "allowPublicPhone" BOOLEAN
        NOT NULL
        DEFAULT FALSE,

    "note" TEXT,

    CONSTRAINT "fkOwnerProfilesUser"
        FOREIGN KEY ("userID")
        REFERENCES auth.users ("userID")
        ON DELETE RESTRICT
);


/* =========================================================
   2. SPECIES
   ========================================================= */

CREATE TABLE IF NOT EXISTS medical.species (
    "speciesID" BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    "name" VARCHAR(100)
        NOT NULL
        UNIQUE,

    "isActive" BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    CONSTRAINT "ckSpeciesNameNotBlank"
        CHECK (LENGTH(TRIM("name")) > 0)
);


/* =========================================================
   3. BREEDS
   Species 1 ---- N Breed
   ========================================================= */

CREATE TABLE IF NOT EXISTS medical.breeds (
    "breedID" BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    "speciesID" BIGINT
        NOT NULL,

    "name" VARCHAR(120)
        NOT NULL,

    "isActive" BOOLEAN
        NOT NULL
        DEFAULT TRUE,

    CONSTRAINT "fkBreedsSpecies"
        FOREIGN KEY ("speciesID")
        REFERENCES medical.species ("speciesID")
        ON DELETE RESTRICT,

    CONSTRAINT "uqBreedsSpeciesName"
        UNIQUE ("speciesID", "name"),

    CONSTRAINT "uqBreedsIDSpecies"
        UNIQUE ("breedID", "speciesID"),

    CONSTRAINT "ckBreedsNameNotBlank"
        CHECK (LENGTH(TRIM("name")) > 0)
);


/* =========================================================
   4. PETS
   OwnerProfile 1 ---- N Pet
   ========================================================= */

CREATE TABLE IF NOT EXISTS medical.pets (
    "petID" BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    "ownerID" BIGINT
        NOT NULL,

    "speciesID" BIGINT
        NOT NULL,

    "breedID" BIGINT,

    "name" VARCHAR(150)
        NOT NULL,

    "petCode" VARCHAR(30)
        NOT NULL
        UNIQUE,

    "sex" VARCHAR(10)
        NOT NULL
        DEFAULT 'UNKNOWN',

    "dateOfBirth" DATE,

    "color" VARCHAR(100),

    "sterilized" BOOLEAN,

    "microchipNumber" VARCHAR(100)
        UNIQUE,

    "photoUrl" TEXT,

    "allergies" TEXT,

    "chronicConditions" TEXT,

    "publicToken" VARCHAR(128)
        NOT NULL
        UNIQUE,

    "status" VARCHAR(20)
        NOT NULL
        DEFAULT 'ACTIVE',

    "note" TEXT,

    "createdAt" TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    "updatedAt" TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "fkPetsOwner"
        FOREIGN KEY ("ownerID")
        REFERENCES medical."ownerProfiles" ("ownerID")
        ON DELETE RESTRICT,

    CONSTRAINT "fkPetsSpecies"
        FOREIGN KEY ("speciesID")
        REFERENCES medical.species ("speciesID")
        ON DELETE RESTRICT,

    CONSTRAINT "fkPetsBreedSpecies"
        FOREIGN KEY ("breedID", "speciesID")
        REFERENCES medical.breeds ("breedID", "speciesID")
        ON DELETE RESTRICT,

    CONSTRAINT "ckPetsNameNotBlank"
        CHECK (LENGTH(TRIM("name")) > 0),

    CONSTRAINT "ckPetsSex"
        CHECK (
            "sex" IN (
                'MALE',
                'FEMALE',
                'UNKNOWN'
            )
        ),

    CONSTRAINT "ckPetsStatus"
        CHECK (
            "status" IN (
                'ACTIVE',
                'DECEASED',
                'INACTIVE'
            )
        ),

    CONSTRAINT "ckPetsPetCodeNotBlank"
        CHECK (LENGTH(TRIM("petCode")) > 0),

    CONSTRAINT "ckPetsPublicTokenNotBlank"
        CHECK (LENGTH(TRIM("publicToken")) > 0)
);


/* =========================================================
   5. INDEXES
   ========================================================= */

CREATE INDEX IF NOT EXISTS "idxBreedsSpecies"
ON medical.breeds ("speciesID");

CREATE INDEX IF NOT EXISTS "idxPetsOwner"
ON medical.pets ("ownerID");

CREATE INDEX IF NOT EXISTS "idxPetsSpecies"
ON medical.pets ("speciesID");

CREATE INDEX IF NOT EXISTS "idxPetsBreedSpecies"
ON medical.pets ("breedID", "speciesID");

CREATE INDEX IF NOT EXISTS "idxPetsStatus"
ON medical.pets ("status");

CREATE INDEX IF NOT EXISTS "idxPetsCreatedAt"
ON medical.pets ("createdAt" DESC);

COMMIT;
