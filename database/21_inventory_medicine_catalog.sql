BEGIN;

CREATE SCHEMA IF NOT EXISTS inventory;

CREATE TABLE IF NOT EXISTS inventory."productCategories" (
    "productCategoryID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name" VARCHAR(150) NOT NULL
        CHECK (length(trim("name")) > 0),
    "description" TEXT,
    "isActive" BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS inventory.products (
    "productID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "categoryID" BIGINT NOT NULL
        REFERENCES inventory."productCategories"("productCategoryID") ON DELETE RESTRICT,
    "productCode" VARCHAR(50) NOT NULL UNIQUE
        CHECK (length(trim("productCode")) > 0),
    "name" VARCHAR(200) NOT NULL
        CHECK (length(trim("name")) > 0),
    "description" TEXT,
    "unit" VARCHAR(50) NOT NULL
        CHECK (length(trim("unit")) > 0),
    "salePrice" NUMERIC(14,2) NOT NULL CHECK ("salePrice" >= 0),
    "minimumStock" NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK ("minimumStock" >= 0),
    "isSellable" BOOLEAN NOT NULL DEFAULT true,
    "status" VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK ("status" IN ('ACTIVE', 'INACTIVE')),
    "createdAt" TIMESTAMPTZ NOT NULL DEFAULT now(),
    "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS inventory."medicineProfiles" (
    "medicineProfileID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "productID" BIGINT NOT NULL UNIQUE
        REFERENCES inventory.products("productID") ON DELETE RESTRICT,
    "activeIngredient" VARCHAR(255) NOT NULL
        CHECK (length(trim("activeIngredient")) > 0),
    "strength" VARCHAR(150) NOT NULL
        CHECK (length(trim("strength")) > 0),
    "dosageForm" VARCHAR(100) NOT NULL
        CHECK (length(trim("dosageForm")) > 0),
    "requiresPrescription" BOOLEAN NOT NULL DEFAULT true
);

CREATE INDEX IF NOT EXISTS "idxInventoryProductsCategory"
    ON inventory.products ("categoryID");
CREATE INDEX IF NOT EXISTS "idxInventoryProductsStatusName"
    ON inventory.products ("status", "name");

COMMENT ON TABLE inventory."productCategories" IS
    'Danh mục nhóm sản phẩm theo thiết kế đồ án; nền cho products.';
COMMENT ON TABLE inventory.products IS
    'Danh mục sản phẩm, không phải số tồn kho. Chỉ sản phẩm ACTIVE có medicineProfiles mới được kê đơn.';
COMMENT ON TABLE inventory."medicineProfiles" IS
    'Hồ sơ chuyên môn thuốc, một hồ sơ cho một sản phẩm. Dữ liệu chuyên môn do người phụ trách cung cấp.';
COMMENT ON COLUMN inventory.products."updatedAt" IS
    'Mặc định khi tạo; module cập nhật danh mục phải cập nhật trường này khi sửa. Không phải audit log.';
COMMENT ON COLUMN inventory.products."salePrice" IS
    'Giá danh mục; kê đơn không tự lập hóa đơn hoặc chốt giá thanh toán.';

COMMIT;

