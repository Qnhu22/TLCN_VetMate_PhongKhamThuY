/* =========================================================
   1. USERS
   Tài khoản người dùng trong hệ thống
   ========================================================= */

CREATE TABLE IF NOT EXISTS auth.users (
    "userID" BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    "email" VARCHAR(255)
        NOT NULL
        UNIQUE,

    "passwordHash" VARCHAR(255)
        NOT NULL,

    "fullName" VARCHAR(150)
        NOT NULL,

    "phone" VARCHAR(20),

    "avatarUrl" TEXT,

    "status" VARCHAR(30)
        NOT NULL
        DEFAULT 'PENDING_VERIFICATION',

    "lastLoginAt" TIMESTAMPTZ,

    "createdAt" TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    "updatedAt" TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "ckUsersStatus"
        CHECK (
            "status" IN (
                'ACTIVE',
                'LOCKED',
                'INACTIVE',
                'PENDING_VERIFICATION'
            )
        )
);


/* =========================================================
   2. ROLES
   Các vai trò trong hệ thống
   Ví dụ:
   PET_OWNER
   VETERINARIAN
   RECEPTIONIST
   CLINIC_MANAGER
   SYSTEM_ADMIN
   ========================================================= */

CREATE TABLE IF NOT EXISTS auth.roles (
    "roleID" BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    "roleCode" VARCHAR(50)
        NOT NULL
        UNIQUE,

    "name" VARCHAR(100)
        NOT NULL,

    "description" TEXT,

    "isActive" BOOLEAN
        NOT NULL
        DEFAULT TRUE
);


/* =========================================================
   3. PERMISSIONS
   Danh mục các quyền chức năng
   ========================================================= */

CREATE TABLE IF NOT EXISTS auth.permissions (
    "permissionID" BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    "permissionCode" VARCHAR(100)
        NOT NULL
        UNIQUE,

    "name" VARCHAR(150)
        NOT NULL,

    "description" TEXT,

    "module" VARCHAR(50)
        NOT NULL,

    "isActive" BOOLEAN
        NOT NULL
        DEFAULT TRUE
);


/* =========================================================
   4. USER ROLES
   Quan hệ N-N giữa User và Role

   Một User có thể có nhiều Role.
   Một Role có thể được gán cho nhiều User.
   ========================================================= */

CREATE TABLE IF NOT EXISTS auth."userRoles" (
    "userID" BIGINT
        NOT NULL,

    "roleID" BIGINT
        NOT NULL,

    "assignedAt" TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (
        "userID",
        "roleID"
    ),

    CONSTRAINT "fkUserRolesUser"
        FOREIGN KEY ("userID")
        REFERENCES auth.users ("userID")
        ON DELETE CASCADE,

    CONSTRAINT "fkUserRolesRole"
        FOREIGN KEY ("roleID")
        REFERENCES auth.roles ("roleID")
        ON DELETE CASCADE
);


/* =========================================================
   5. ROLE PERMISSIONS
   Quan hệ N-N giữa Role và Permission

   Một Role có nhiều Permission.
   Một Permission có thể thuộc nhiều Role.
   ========================================================= */

CREATE TABLE IF NOT EXISTS auth."rolePermissions" (
    "roleID" BIGINT
        NOT NULL,

    "permissionID" BIGINT
        NOT NULL,

    PRIMARY KEY (
        "roleID",
        "permissionID"
    ),

    CONSTRAINT "fkRolePermissionsRole"
        FOREIGN KEY ("roleID")
        REFERENCES auth.roles ("roleID")
        ON DELETE CASCADE,

    CONSTRAINT "fkRolePermissionsPermission"
        FOREIGN KEY ("permissionID")
        REFERENCES auth.permissions ("permissionID")
        ON DELETE CASCADE
);


/* =========================================================
   6. VERIFICATION TOKENS
   Token/OTP dùng cho:
   - Xác minh email
   - Đặt lại mật khẩu
   ========================================================= */

CREATE TABLE IF NOT EXISTS auth."verificationTokens" (
    "verificationTokenID" BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    "userID" BIGINT
        NOT NULL,

    "purpose" VARCHAR(30)
        NOT NULL,

    "tokenHash" VARCHAR(255)
        NOT NULL,

    "expiresAt" TIMESTAMPTZ
        NOT NULL,

    "usedAt" TIMESTAMPTZ,

    "createdAt" TIMESTAMPTZ
        NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "fkVerificationTokensUser"
        FOREIGN KEY ("userID")
        REFERENCES auth.users ("userID")
        ON DELETE CASCADE,

    CONSTRAINT "ckVerificationTokensPurpose"
        CHECK (
            "purpose" IN (
                'EMAIL_VERIFICATION',
                'PASSWORD_RESET'
            )
        )
);


/* =========================================================
   7. INDEXES
   Hỗ trợ tìm token theo User + Purpose
   và dọn/tìm token hết hạn.
   ========================================================= */

CREATE INDEX IF NOT EXISTS
    "idxVerificationTokensUserPurpose"
ON auth."verificationTokens" (
    "userID",
    "purpose"
);


CREATE INDEX IF NOT EXISTS
    "idxVerificationTokensExpiresAt"
ON auth."verificationTokens" (
    "expiresAt"
);